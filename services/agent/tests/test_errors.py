"""Errors must look like the Go services': {"error": "...", "request_id": "..."}.

web/lib/api.ts reads the "error" field from every service, so this
shape is part of the contract between services.
"""

from fastapi.testclient import TestClient

from agent.main import app

client = TestClient(app)


def test_unknown_path_uses_shared_error_shape():
    res = client.get("/nope", headers={"X-Request-ID": "req-1"})
    assert res.status_code == 404
    assert res.json() == {"error": "not found", "request_id": "req-1"}


def test_wrong_method_uses_shared_error_shape():
    res = client.post("/health")
    assert res.status_code == 405
    assert res.json()["error"] == "method not allowed"
    assert res.json()["request_id"]  # generated by the middleware
